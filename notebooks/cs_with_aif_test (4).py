# ------------------------------------------------------------
# BUILD A MATRIX: Observation Model p(o|s)
# ------------------------------------------------------------
# This defines the likelihood of observations given hidden states

def build_A_matrix(num_obs, num_states):
    """
    Build observation model A where A[modality][obs, state] = p(obs|state)

    Modality 0: Surprisal observations
      - low_load state → more likely to observe low surprisal
      - high_load state → more likely to observe high surprisal

    Modality 1: Length observations
      - low_load state → more likely short/medium sentences
      - high_load state → more likely medium/long sentences

    Modality 2: Switch observations
      - This will be determined by the agent's actions, not directly by state
      - We make it deterministic based on the action taken
    """
    A = utils.obj_array(num_modalities)

    # Modality 0: Surprisal
    # Shape: [3 surprisal levels, 2 states]
    A[0] = np.array([
        [0.6, 0.2],  # low surprisal: more likely in low_load
        [0.3, 0.3],  # medium surprisal: neutral
        [0.1, 0.5]   # high surprisal: more likely in high_load
    ])
    # Normalize columns
    A[0] = A[0] / A[0].sum(axis=0, keepdims=True)

    # Modality 1: Sentence length
    # Shape: [3 length levels, 2 states]
    A[1] = np.array([
        [0.5, 0.2],  # short: more likely in low_load
        [0.3, 0.3],  # medium: neutral
        [0.2, 0.5]   # long: more likely in high_load
    ])
    A[1] = A[1] / A[1].sum(axis=0, keepdims=True)

    # Modality 2: Code-switch outcome
    # This is deterministic based on action, not state
    # We'll handle this specially - for now make it uniform
    A[2] = np.ones((num_obs_switch, num_states)) / num_obs_switch

    return A

A = build_A_matrix(num_obs, num_states)

