def evaluate_model(model_name, value_fn, data, verbose=False):
    """
    Evaluate a model on the code-switching data

    For each sentence:
    1. Observe surprisal and length
    2. Infer cognitive state beliefs
    3. Use value function to get C, E, gamma
    4. Compute action probabilities
    5. Compare to actual code-switching outcome
    6. Accumulate log-likelihood

    Parameters:
    -----------
    model_name : str
        Name of model (M1, M2, M3)
    value_fn : function
        Value function that returns (C, E, gamma) given beliefs
    data : DataFrame
        Code-switching dataset
    verbose : bool
        Print progress

    Returns:
    --------
    results : dict
        Contains log_likelihoods, accuracy, inferred_states, etc.
    """
    print(f"\n{'='*60}")
    print(f"EVALUATING {model_name}")
    print(f"{'='*60}")

    n_samples = len(data)
    log_likelihoods = []
    inferred_states = []
    gammas = []
    predictions = []

    # Create agent for inference
    C_init = utils.obj_array(num_modalities)
    for m in range(num_modalities):
        C_init[m] = np.ones(num_obs[m]) / num_obs[m]

    agent = Agent(
        A=A,
        B=B,
        C=C_init,  # Will be overridden by value function
        D=D,
        policy_len=1,
        inference_horizon=1,
        control_fac_idx=[0],
        use_utility=True,
        use_states_info_gain=False,
        action_selection="stochastic",
        gamma=16.0  # Will be overridden by value function
    )

    # Process each sentence
    for idx in range(n_samples):
        if verbose and idx % 500 == 0:
            print(f"Processing sentence {idx}/{n_samples}...")

        # Get observations for this sentence
        obs_surprisal_idx = int(data.iloc[idx]['surprisal_idx'])
        obs_length_idx = int(data.iloc[idx]['length_idx'])
        actual_switch = int(data.iloc[idx]['cs_binary'])

        # Observation: [surprisal, length, switch_outcome]
        obs = [obs_surprisal_idx, obs_length_idx, actual_switch]

        # State inference: Given surprisal and length, what cognitive state are we in?
        # We only use modalities 0 and 1 for inference (not the switch outcome)
        obs_for_inference = [obs_surprisal_idx, obs_length_idx, 0]  # Placeholder for switch

        # Infer state beliefs using only surprisal and length
        # Compute posterior: p(s|o_surprisal, o_length) ∝ p(o_surprisal|s) * p(o_length|s) * p(s)
        likelihood_surprisal = A[0][obs_surprisal_idx, :]
        likelihood_length = A[1][obs_length_idx, :]
        prior = D[0]

        posterior = likelihood_surprisal * likelihood_length * prior
        posterior = posterior / (posterior.sum() + 1e-12)

        # Get value function parameters based on current beliefs
        C_t, E_t, gamma_t = value_fn(posterior, idx)

        # Compute action probabilities given the inferred state and preferences
        # We need to compute Q(π) = expected free energy for each policy
        # Then action_probs = softmax(gamma * Q)

        # For simplicity, we'll use a direct mapping:
        # The agent prefers outcomes specified in C and policies specified in E
        # Action probabilities come from policy probabilities weighted by their outcomes

        # Policy 0: maintain_chinese (no switch)
        # Policy 1: switch_to_english (switch)

        # The probability of each action depends on:
        # 1. Outcome preferences C[2] (how much we want no_switch vs switch)
        # 2. Policy priors E (if specified)
        # 3. Precision gamma (how strongly we follow preferences)

        if E_t is not None:
            # Use policy priors weighted by outcome preferences
            policy_logits = np.log(E_t + 1e-12) + gamma_t * np.log(C_t[2] + 1e-12)
        else:
            # Use outcome preferences directly
            policy_logits = gamma_t * np.log(C_t[2] + 1e-12)

        action_probs = softmax(policy_logits)

        # Probability of the actual observed action
        prob_actual_action = action_probs[actual_switch]
        log_lik = np.log(prob_actual_action + 1e-12)

        # Store results
        log_likelihoods.append(log_lik)
        inferred_states.append(posterior)
        gammas.append(gamma_t)
        predictions.append(action_probs[1])  # Probability of switch

    # Compute summary statistics
    total_log_lik = np.sum(log_likelihoods)
    mean_log_lik = np.mean(log_likelihoods)

    # Accuracy: predict switch if prob > 0.5
    predicted_switches = np.array(predictions) > 0.5
    actual_switches = data['cs_binary'].values
    accuracy = np.mean(predicted_switches == actual_switches)

    # AIC and BIC
    # Number of parameters:
    # M1: 1 (gamma)
    # M2: 2 (gamma_base, k)
    # M3: 2 profiles * 3 params (phi, xi, gamma) + Z assignment = 6 + 4 = 10
    n_params = {'M1': 1, 'M2': 2, 'M3': 10}[model_name]
    aic = 2 * n_params - 2 * total_log_lik
    bic = n_params * np.log(n_samples) - 2 * total_log_lik

    results = {
        'model_name': model_name,
        'log_likelihoods': np.array(log_likelihoods),
        'total_log_lik': total_log_lik,
        'mean_log_lik': mean_log_lik,
        'accuracy': accuracy,
        'aic': aic,
        'bic': bic,
        'n_params': n_params,
        'inferred_states': np.array(inferred_states),
        'gammas': np.array(gammas),
        'predictions': np.array(predictions)
    }

    print(f"\nResults for {model_name}:")
    print(f"  Total Log-Likelihood: {total_log_lik:.2f}")
    print(f"  Mean Log-Likelihood:  {mean_log_lik:.4f}")
    print(f"  Accuracy:             {accuracy:.4f}")
    print(f"  AIC:                  {aic:.2f}")
    print(f"  BIC:                  {bic:.2f}")
    print(f"  Mean Gamma:           {np.mean(gammas):.4f}")
    print(f"  Std Gamma:            {np.std(gammas):.4f}")

    return results

