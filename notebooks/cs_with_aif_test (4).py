def test_discretization_sensitivity(data, n_bins_list=[2, 3, 4, 5, 6, 7]):
    """
    Test how model performance changes with different discretization schemes.

    FIXED: Now properly handles cases where pd.cut creates fewer bins than requested
    due to duplicate percentile boundaries.
    """
    import pandas as pd
    import numpy as np
    from pymdp import utils, control

    results_by_binning = {}

    for n_bins in n_bins_list:
        print(f"\n{'='*60}")
        print(f"Testing with {n_bins} bins")
        print(f"{'='*60}")

        # Create a copy of the data for this binning scheme
        data_binned = data.copy()

        # Re-discretize surprisal into n_bins categories
        # Using quantile-based binning to ensure roughly equal numbers in each bin
        try:
            # Use qcut instead of cut for more reliable binning
            data_binned['surprisal_idx'] = pd.qcut(
                data['surprisal_first_cs_word_trans'],
                q=n_bins,
                labels=False,
                duplicates='drop'
            ).astype(int)

            # Get actual number of bins created for surprisal
            n_bins_surprisal_actual = data_binned['surprisal_idx'].nunique()

        except Exception as e:
            print(f"  Warning: Failed to create {n_bins} bins for surprisal: {e}")
            print(f"  Skipping this bin count...")
            continue

        # Re-discretize length into n_bins categories
        try:
            data_binned['length_idx'] = pd.qcut(
                data['translation_sentence_length'],
                q=n_bins,
                labels=False,
                duplicates='drop'
            ).astype(int)

            # Get actual number of bins created for length
            n_bins_length_actual = data_binned['length_idx'].nunique()

        except Exception as e:
            print(f"  Warning: Failed to create {n_bins} bins for length: {e}")
            print(f"  Skipping this bin count...")
            continue

        # CRITICAL FIX: Use the ACTUAL number of bins created
        print(f"  Requested {n_bins} bins")
        print(f"  Actually created: {n_bins_surprisal_actual} surprisal bins, {n_bins_length_actual} length bins")

        # Check if we lost too many bins
        if n_bins_surprisal_actual < n_bins * 0.7 or n_bins_length_actual < n_bins * 0.7:
            print(f"  Warning: Lost >30% of requested bins due to duplicate values")
            print(f"  Skipping this configuration...")
            continue

        # Build new A matrix using ACTUAL bin counts
        num_modalities = 3
        num_states = 2
        num_obs_switch = 2

        A_new = utils.obj_array(num_modalities)

        # Modality 0: Surprisal observations (n_bins_surprisal_actual levels)
        A_new[0] = np.zeros((n_bins_surprisal_actual, num_states))
        for obs in range(n_bins_surprisal_actual):
            # Low-load state: more probability on low surprisal bins
            A_new[0][obs, 0] = np.exp(-(obs / n_bins_surprisal_actual) * 2)
            # High-load state: more probability on high surprisal bins
            A_new[0][obs, 1] = np.exp(-((n_bins_surprisal_actual - 1 - obs) / n_bins_surprisal_actual) * 2)
        A_new[0] = A_new[0] / A_new[0].sum(axis=0, keepdims=True)

        # Modality 1: Length observations (n_bins_length_actual levels)
        A_new[1] = np.zeros((n_bins_length_actual, num_states))
        for obs in range(n_bins_length_actual):
            A_new[1][obs, 0] = np.exp(-(obs / n_bins_length_actual) * 1.5)
            A_new[1][obs, 1] = np.exp(-((n_bins_length_actual - 1 - obs) / n_bins_length_actual) * 1.5)
        A_new[1] = A_new[1] / A_new[1].sum(axis=0, keepdims=True)

        # Modality 2: Switch outcome (always 2 levels)
        A_new[2] = np.ones((num_obs_switch, num_states)) / num_obs_switch

        # Verify observation indices are valid
        max_surprisal_idx = data_binned['surprisal_idx'].max()
        max_length_idx = data_binned['length_idx'].max()
        print(f"  Max surprisal index: {max_surprisal_idx}, A[0] shape: {A_new[0].shape}")
        print(f"  Max length index: {max_length_idx}, A[1] shape: {A_new[1].shape}")

        if max_surprisal_idx >= A_new[0].shape[0]:
            print(f"  ERROR: Surprisal index {max_surprisal_idx} exceeds A matrix size {A_new[0].shape[0]}")
            continue
        if max_length_idx >= A_new[1].shape[0]:
            print(f"  ERROR: Length index {max_length_idx} exceeds A matrix size {A_new[1].shape[0]}")
            continue

        # Create D matrix (prior over states)
        D_new = utils.obj_array_zeros([[num_states]])
        D_new[0] = np.array([0.5, 0.5])

        # Create Z matrix (state-to-profile assignment)
        num_profiles = 2
        Z_new = np.array([[0.9, 0.1],   # low_load primarily recruits profile 0
                          [0.1, 0.9]])   # high_load primarily recruits profile 1

        # Set up policies
        num_actions = [2]  # Binary: maintain language or switch
        policies_new = control.construct_policies([num_states], num_actions, policy_len=1)

        # Train M3 with this discretization using cross-validation
        from sklearn.model_selection import KFold

        pair_ids_sens = data_binned['pair_id'].unique()
        kf_sens = KFold(n_splits=3, shuffle=True, random_state=42)

        cv_results_sens = []

        for fold_idx, (train_idx, test_idx) in enumerate(kf_sens.split(pair_ids_sens)):
            train_pairs = pair_ids_sens[train_idx]
            test_pairs = pair_ids_sens[test_idx]

            train_data_sens = data_binned[data_binned['pair_id'].isin(train_pairs)]
            test_data_sens = data_binned[data_binned['pair_id'].isin(test_pairs)]

            # Train M3 on this fold with new discretization
            try:
                # You'll need to import or define these functions from your original script
                learned_params_sens = fit_M3_parameters(
                    train_data_sens,
                    A_new, D_new, Z_new,
                    learn_Z=False,
                    n_restarts=2
                )

                # Create value function
                value_fn_sens = make_value_fn_M3(
                    profiles=learned_params_sens['profiles'],
                    Z=learned_params_sens['Z'],
                    policies=policies_new,
                    num_actions_per_factor=num_actions
                )

                # Evaluate on test set
                results_sens = evaluate_model('M3', value_fn_sens, test_data_sens, verbose=False)
                cv_results_sens.append(results_sens)

            except Exception as e:
                print(f"  Warning: Fold {fold_idx + 1} failed with error: {e}")
                import traceback
                traceback.print_exc()
                continue

        if len(cv_results_sens) > 0:
            mean_accuracy = np.mean([r['accuracy'] for r in cv_results_sens])
            mean_log_lik = np.mean([r['total_log_lik'] for r in cv_results_sens])

            results_by_binning[n_bins] = {
                'accuracy': mean_accuracy,
                'log_lik': mean_log_lik,
                'n_folds': len(cv_results_sens),
                'n_bins_actual_surprisal': n_bins_surprisal_actual,
                'n_bins_actual_length': n_bins_length_actual
            }

            print(f"Mean Accuracy with {n_bins} bins ({n_bins_surprisal_actual}/{n_bins_length_actual} actual): {mean_accuracy:.4f}")
            print(f"Mean Log-Lik with {n_bins} bins: {mean_log_lik:.2f}")
        else:
            print(f"All folds failed for {n_bins} bins - skipping")

    return results_by_binning

